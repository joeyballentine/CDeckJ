//! Which MIDI message is which control: the DDJ-GRV6 defaults, overridable in the settings file.

use serde::{Deserialize, Serialize};

/// Note and CC numbers. Deck controls use status 0x90/0xB0 + deck channel (0..3),
/// global controls use channel `global_channel`, pads use `pad_status` + 2·deck (+1 = SHIFT).
#[derive(Clone, Debug, Serialize, Deserialize, PartialEq)]
#[serde(default)]
pub struct MidiMap {
    pub port_hints: Vec<String>,
    pub invert_tempo: bool,
    /// Jog ticks per platter revolution (scratch sensitivity).
    pub jog_ticks_per_rev: f64,
    pub play: u8,
    pub shift_play: u8,
    pub cue: u8,
    pub shift_cue: u8,
    pub sync: u8,
    pub shift_sync: u8,
    pub shift: u8,
    pub jog_touch: u8,
    pub shift_jog_touch: u8,
    pub loop_in: u8,
    pub loop_out: u8,
    pub reloop: u8,
    pub shift_loop_in: u8,
    pub shift_loop_out: u8,
    pub shift_reloop: u8,
    pub pfl: u8,
    pub cc_tempo: u8,
    pub cc_trim: u8,
    pub cc_hi: u8,
    pub cc_mid: u8,
    pub cc_low: u8,
    pub cc_fader: u8,
    pub cc_jog_bend: u8,
    pub cc_jog_scratch: u8,
    pub cc_jog_bend_top: u8,
    pub cc_jog_search: Vec<u8>,
    pub global_channel: u8,
    pub browse_press: u8,
    pub shift_browse_press: u8,
    /// The GRV6's browse knob tilts: BACK (left) and VIEW. Pioneer's usual notes for BACK
    /// (0x65, SHIFT 0x66); VIEW (0x7A, SHIFT 0x67) is from the GRV6 MIDI list's ordering.
    pub back: u8,
    pub shift_back: u8,
    pub view: u8,
    pub shift_view: u8,
    pub load_base: u8,
    pub cc_browse: u8,
    pub cc_crossfader: u8,
    pub cc_head_mix: u8,
    pub cc_head_level: u8,
    pub cc_color_fx_base: u8,
    pub pad_status: u8,
    pub pad_hot_cue: u8,
    pub pad_beat_jump: u8,
    pub pad_beat_loop: u8,
    /// BEAT FX section (DDJ-400/FLX layout: MIDI channel 5).
    pub fx_channel: u8,
    pub fx_select: u8,
    pub fx_beat_left: u8,
    pub fx_beat_right: u8,
    pub fx_ch1: u8,
    pub fx_ch2: u8,
    pub fx_master: u8,
    pub fx_on: u8,
    pub cc_fx_level: u8,
    /// Channel level indicators: CDeckJ sends each channel's level (0–127) as this CC on
    /// the deck's MIDI channel. The controller's meters show nothing unless the software
    /// drives them.
    pub cc_level_meter: u8,
}

impl Default for MidiMap {
    fn default() -> Self {
        Self {
            port_hints: ["GRV6", "DDJ", "AlphaTheta", "Pioneer"].map(String::from).to_vec(),
            invert_tempo: false,
            jog_ticks_per_rev: 720.0,
            play: 0x0B,
            shift_play: 0x47,
            cue: 0x0C,
            shift_cue: 0x48,
            sync: 0x58,
            shift_sync: 0x5C,
            shift: 0x3F,
            jog_touch: 0x36,
            shift_jog_touch: 0x67,
            loop_in: 0x10,
            loop_out: 0x11,
            reloop: 0x4D,
            shift_loop_in: 0x4C,
            shift_loop_out: 0x4E,
            shift_reloop: 0x50,
            pfl: 0x54,
            cc_tempo: 0x00,
            cc_trim: 0x04,
            cc_hi: 0x07,
            cc_mid: 0x0B,
            cc_low: 0x0F,
            cc_fader: 0x13,
            cc_jog_bend: 0x21,
            cc_jog_scratch: 0x22,
            cc_jog_bend_top: 0x23,
            cc_jog_search: vec![0x26, 0x29],
            global_channel: 6,
            browse_press: 0x41,
            shift_browse_press: 0x42,
            back: 0x65,
            shift_back: 0x66,
            view: 0x7A,
            shift_view: 0x67,
            load_base: 0x46,
            cc_browse: 0x40,
            cc_crossfader: 0x1F,
            cc_head_mix: 0x0C,
            cc_head_level: 0x0D,
            cc_color_fx_base: 0x17,
            pad_status: 0x97,
            pad_hot_cue: 0x00,
            pad_beat_jump: 0x20,
            pad_beat_loop: 0x60,
            fx_channel: 4,
            fx_select: 0x63,
            fx_beat_left: 0x4A,
            fx_beat_right: 0x4B,
            fx_ch1: 0x10,
            fx_ch2: 0x11,
            fx_master: 0x14,
            fx_on: 0x47,
            cc_fx_level: 0x02,
            cc_level_meter: 0x02,
        }
    }
}
